-- ---------------------------------------------------------------------------
-- 4. Funciones de contexto (GUC por petición, nunca confiable desde el cliente)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_app_establishment_id()
RETURNS BIGINT LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('app.current_establishment_id', true), '')::bigint;
$$;

CREATE OR REPLACE FUNCTION fn_app_is_superadmin()
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
  SELECT COALESCE(current_setting('app.current_role', true), '') = 'SUPERADMINISTRADOR';
$$;

CREATE OR REPLACE FUNCTION fn_app_is_system()
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
  SELECT COALESCE(current_setting('app.current_role', true), '') = 'SYSTEM';
$$;

-- ---------------------------------------------------------------------------
-- 5. Row Level Security: fuente de verdad del aislamiento en la base de datos
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  t TEXT;
BEGIN
  -- Inventario: el superadministrador NO tiene acceso, ni siquiera a nivel BD.
  FOREACH t IN ARRAY ARRAY[
    'categories','suppliers','products','product_suppliers',
    'inventory_movements','product_alert_settings'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I
      USING (fn_app_is_system() OR establishment_id = fn_app_establishment_id())
      WITH CHECK (fn_app_is_system() OR establishment_id = fn_app_establishment_id())
    $p$, t);
  END LOOP;

  -- Administración global: solo el superadministrador ve todas las cuentas.
  FOREACH t IN ARRAY ARRAY['users','audit_log','system_settings'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I
      USING (
        fn_app_is_system() OR fn_app_is_superadmin()
        OR establishment_id = fn_app_establishment_id()
      )
      WITH CHECK (
        fn_app_is_system() OR fn_app_is_superadmin()
        OR establishment_id = fn_app_establishment_id()
      )
    $p$, t);
  END LOOP;
END $$;

-- El superadministrador no tiene establishment_id; política específica.
DROP POLICY IF EXISTS own_establishment_read ON establishments;
CREATE POLICY own_establishment_read ON establishments
  USING (
    fn_app_is_system() OR fn_app_is_superadmin() OR id = fn_app_establishment_id()
  )
  WITH CHECK (fn_app_is_system() OR fn_app_is_superadmin());

-- ---------------------------------------------------------------------------
-- 6. Movimientos: preserva el bloqueo FOR UPDATE y deriva el tenant del producto
-- ---------------------------------------------------------------------------
DROP FUNCTION IF EXISTS fn_register_movement(
  BIGINT, VARCHAR, NUMERIC, BIGINT, BIGINT, VARCHAR, TEXT, TIMESTAMPTZ, VARCHAR
);

CREATE OR REPLACE FUNCTION fn_register_movement(
  p_product_id    BIGINT,
  p_type          VARCHAR(3),
  p_quantity      NUMERIC,
  p_user_id       BIGINT,
  p_supplier_id   BIGINT DEFAULT NULL,
  p_reason        VARCHAR(180) DEFAULT NULL,
  p_notes         TEXT DEFAULT NULL,
  p_movement_date TIMESTAMPTZ DEFAULT now(),
  p_source_key    VARCHAR(80) DEFAULT NULL
)
RETURNS BIGINT AS $$
DECLARE
  v_stock_before NUMERIC(14,3);
  v_stock_after  NUMERIC(14,3);
  v_delta        NUMERIC(14,3);
  v_active       BOOLEAN;
  v_establishment_id BIGINT;
  v_movement_id  BIGINT;
BEGIN
  IF p_quantity IS NULL OR p_quantity <= 0 THEN
    RAISE EXCEPTION 'INVALID_QUANTITY' USING ERRCODE = '22023';
  END IF;
  IF p_type NOT IN ('IN', 'OUT') THEN
    RAISE EXCEPTION 'INVALID_MOVEMENT_TYPE' USING ERRCODE = '22023';
  END IF;
  IF p_type = 'OUT' AND (p_reason IS NULL OR btrim(p_reason) = '') THEN
    RAISE EXCEPTION 'REASON_REQUIRED' USING ERRCODE = '22023';
  END IF;

  SELECT quantity, active, establishment_id
    INTO v_stock_before, v_active, v_establishment_id
    FROM products
   WHERE id = p_product_id
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'PRODUCT_NOT_FOUND' USING ERRCODE = 'P0002';
  END IF;
  IF NOT v_active THEN
    RAISE EXCEPTION 'PRODUCT_INACTIVE' USING ERRCODE = '23514';
  END IF;

  v_delta       := CASE WHEN p_type = 'IN' THEN p_quantity ELSE -p_quantity END;
  v_stock_after := v_stock_before + v_delta;
  IF v_stock_after < 0 THEN
    RAISE EXCEPTION 'INSUFFICIENT_STOCK' USING ERRCODE = '23514';
  END IF;

  UPDATE products
     SET quantity = v_stock_after, last_movement_at = now()
   WHERE id = p_product_id;

  INSERT INTO inventory_movements (
    establishment_id, product_id, type, quantity, stock_before, stock_after,
    user_id, supplier_id, reason, notes, movement_date, source_key
  ) VALUES (
    v_establishment_id, p_product_id, p_type, p_quantity, v_stock_before, v_stock_after,
    p_user_id, p_supplier_id, p_reason, p_notes, p_movement_date, p_source_key
  )
  RETURNING id INTO v_movement_id;

  RETURN v_movement_id;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- 7. Vista unificada: expone y filtra establishment_id
-- ---------------------------------------------------------------------------
DROP VIEW IF EXISTS v_product_inventory;

CREATE OR REPLACE VIEW v_product_inventory AS
WITH globals AS (
  SELECT
    COALESCE((SELECT value #>> '{}' FROM system_settings
               WHERE key = 'alert.preventive_percentage' AND establishment_id = fn_app_establishment_id())::numeric, 25) AS preventive_percentage,
    COALESCE((SELECT value #>> '{}' FROM system_settings
               WHERE key = 'metrics.analysis_window_days' AND establishment_id = fn_app_establishment_id())::integer, 30) AS window_days,
    COALESCE((SELECT value #>> '{}' FROM system_settings
               WHERE key = 'metrics.min_history_days' AND establishment_id = fn_app_establishment_id())::integer, 7) AS min_history_days
),
base AS (
  SELECT
    p.id, p.establishment_id, p.code, p.name, p.description, p.category_id, p.supplier_id,
    p.purchase_price, p.sale_price, p.quantity, p.min_stock, p.alert_percentage,
    p.active, p.last_movement_at, p.created_at, p.updated_at,
    c.name AS category_name,
    s.name AS supplier_name,
    COALESCE(pas.preventive_percentage, g.preventive_percentage) AS effective_percentage,
    COALESCE(pas.analysis_window_days, g.window_days) AS effective_window_days,
    COALESCE(pas.min_history_days, g.min_history_days) AS effective_min_history_days
  FROM products p
  CROSS JOIN globals g
  LEFT JOIN categories c ON c.id = p.category_id AND c.establishment_id = p.establishment_id
  LEFT JOIN suppliers s ON s.id = p.supplier_id AND s.establishment_id = p.establishment_id
  LEFT JOIN product_alert_settings pas ON pas.product_id = p.id AND pas.establishment_id = p.establishment_id
  WHERE (fn_app_is_system() OR p.establishment_id = fn_app_establishment_id())
    AND NOT fn_app_is_superadmin()
),
movstats AS (
  SELECT
    b.id,
    COALESCE(SUM(m.quantity) FILTER (WHERE m.type = 'OUT'), 0) AS out_units_window,
    COALESCE(SUM(m.quantity) FILTER (WHERE m.type = 'IN'), 0) AS in_units_window,
    COUNT(m.id) FILTER (WHERE m.type = 'OUT')::integer AS out_movements_window,
    MIN(m.movement_date) FILTER (WHERE m.type = 'OUT') AS first_out_window
  FROM base b
  LEFT JOIN inventory_movements m
    ON m.product_id = b.id
   AND m.establishment_id = b.establishment_id
   AND m.movement_date >= now() - (b.effective_window_days || ' days')::interval
  GROUP BY b.id
),
calculated AS (
  SELECT
    b.*,
    b.min_stock * (1 + b.effective_percentage / 100.0) AS preventive_threshold,
    CASE
      WHEN b.quantity = 0 THEN 'AGOTADO'
      WHEN b.quantity <= b.min_stock THEN 'CRITICO'
      WHEN b.quantity <= b.min_stock * (1 + b.effective_percentage / 100.0) THEN 'BAJO'
      ELSE 'NORMAL'
    END AS alert_level,
    m.out_units_window,
    m.in_units_window,
    m.out_movements_window,
    m.first_out_window,
    m.out_units_window / b.effective_window_days::numeric AS avg_daily_out,
    CASE
      WHEN m.out_units_window <= 0 THEN 'NO_CALCULABLE'
      WHEN m.first_out_window > now() - (b.effective_min_history_days || ' days')::interval THEN 'INSUFICIENTE'
      ELSE 'CALCULABLE'
    END AS coverage_status
  FROM base b
  JOIN movstats m ON m.id = b.id
)
SELECT
  c.*,
  CASE
    WHEN c.coverage_status = 'CALCULABLE'
      THEN ROUND(c.quantity / NULLIF(c.avg_daily_out, 0), 2)
    ELSE NULL
  END AS coverage_days,
  ROUND(c.quantity * c.purchase_price, 2) AS inventory_value,
  ROUND(c.quantity * c.sale_price, 2) AS inventory_sale_value
FROM calculated c;

ALTER VIEW v_product_inventory SET (security_barrier = true);

