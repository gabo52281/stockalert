  analysis_window_days  INTEGER NOT NULL DEFAULT 30 CHECK (analysis_window_days BETWEEN 1 AND 365),
  min_history_days      INTEGER NOT NULL DEFAULT 7 CHECK (min_history_days BETWEEN 1 AND 365),
