-- STOCKALERT · Migración 001 · Esquema inicial
-- PostgreSQL 14+. Todas las cantidades son NUMERIC para evitar errores de precisión.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------------------------------------------------------------------------
-- Función genérica de auditoría de updated_at
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- Roles y usuarios
-- ---------------------------------------------------------------------------
CREATE TABLE roles (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(40)  NOT NULL UNIQUE,
  description TEXT
);

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(120) NOT NULL,
  email         VARCHAR(180) NOT NULL UNIQUE,
  password_hash TEXT         NOT NULL,
  role_id       INTEGER      NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
  active        BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT users_email_format CHECK (
    email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
  )
);

CREATE TRIGGER trg_users_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TABLE revoked_tokens (
  jti         VARCHAR(80) PRIMARY KEY,
  user_id     BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  TIMESTAMPTZ NOT NULL,
  revoked_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Catálogos
-- ---------------------------------------------------------------------------
CREATE TABLE categories (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(120) NOT NULL UNIQUE,
  description TEXT,
  active      BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT categories_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TRIGGER trg_categories_updated_at
  BEFORE UPDATE ON categories
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TABLE suppliers (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           VARCHAR(180) NOT NULL,
  tax_id         VARCHAR(40)  UNIQUE,
  phone          VARCHAR(40),
  email          VARCHAR(180),
  address        VARCHAR(255),
  contact_person VARCHAR(120),
  notes          TEXT,
  active         BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT suppliers_name_not_blank CHECK (btrim(name) <> ''),
  CONSTRAINT suppliers_email_format CHECK (
    email IS NULL OR email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
  )
);

CREATE TRIGGER trg_suppliers_updated_at
  BEFORE UPDATE ON suppliers
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------------
-- Productos
-- ---------------------------------------------------------------------------
CREATE TABLE products (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code               VARCHAR(60)   NOT NULL UNIQUE,
  name               VARCHAR(180)  NOT NULL,
  description        TEXT,
  category_id        BIGINT        REFERENCES categories(id) ON DELETE RESTRICT,
  supplier_id        BIGINT        REFERENCES suppliers(id) ON DELETE RESTRICT,
  purchase_price     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (purchase_price >= 0),
  sale_price         NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (sale_price >= 0),
  quantity           NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  min_stock          NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
  alert_percentage   NUMERIC(5,2)  NOT NULL DEFAULT 25 CHECK (alert_percentage >= 0 AND alert_percentage <= 100),
  active             BOOLEAN       NOT NULL DEFAULT TRUE,
  last_movement_at   TIMESTAMPTZ,
  created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT products_code_not_blank CHECK (btrim(code) <> ''),
  CONSTRAINT products_name_not_blank CHECK (btrim(name) <> ''),
  CONSTRAINT products_sale_not_below_purchase CHECK (sale_price >= purchase_price OR sale_price = 0)
);

CREATE TRIGGER trg_products_updated_at
  BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- Relación opcional muchos a muchos producto <-> proveedor
CREATE TABLE product_suppliers (
  product_id   BIGINT  NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  supplier_id  BIGINT  NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
  is_primary   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (product_id, supplier_id)
);

CREATE UNIQUE INDEX uq_product_primary_supplier
  ON product_suppliers (product_id) WHERE is_primary;

-- ---------------------------------------------------------------------------
-- Movimientos de inventario (historial inmutable por diseño de aplicación)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory_movements (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    BIGINT        NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  type          VARCHAR(3)    NOT NULL CHECK (type IN ('IN', 'OUT')),
  quantity      NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
  stock_before  NUMERIC(14,3) NOT NULL CHECK (stock_before >= 0),
  stock_after   NUMERIC(14,3) NOT NULL CHECK (stock_after >= 0),
  user_id       BIGINT        NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  supplier_id   BIGINT        REFERENCES suppliers(id) ON DELETE RESTRICT,
  reason        VARCHAR(180),
  notes         TEXT,
  movement_date TIMESTAMPTZ   NOT NULL DEFAULT now(),
  source_key    VARCHAR(80)   UNIQUE,
  created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT movements_no_supplier_on_output CHECK (type = 'IN' OR supplier_id IS NULL),
  CONSTRAINT movements_reason_required_on_output CHECK (
    type <> 'OUT' OR (reason IS NOT NULL AND btrim(reason) <> '')
  ),
  CONSTRAINT movements_stock_consistency CHECK (
    stock_after = stock_before + CASE WHEN type = 'IN' THEN quantity ELSE -quantity END
  )
);

